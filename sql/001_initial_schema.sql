-- DAI-21 — Esquema inicial do Data AI Job Market Intelligence v2
-- Aplicar em banco vazio 'jobmarket'. A DAI-22 tratará da conexão Python.
BEGIN;

CREATE TABLE IF NOT EXISTS companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    normalized_name TEXT NOT NULL CHECK (length(btrim(normalized_name)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_companies_normalized_name UNIQUE (normalized_name)
);

CREATE TABLE IF NOT EXISTS sources (
    source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
    base_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pipeline_runs (
    pipeline_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'success', 'partial', 'failed')),
    records_fetched INTEGER NOT NULL DEFAULT 0 CHECK (records_fetched >= 0),
    records_valid INTEGER NOT NULL DEFAULT 0 CHECK (records_valid >= 0),
    records_rejected INTEGER NOT NULL DEFAULT 0 CHECK (records_rejected >= 0),
    error_message TEXT,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE IF NOT EXISTS jobs (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(company_id),
    title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    requirements TEXT,
    desirable_requirements TEXT,
    state TEXT,
    city TEXT,
    neighborhood TEXT,
    work_mode TEXT CHECK (work_mode IN ('remote', 'hybrid', 'onsite')),
    seniority_level TEXT,
    employment_type TEXT,
    salary_text TEXT,
    salary_min NUMERIC(14, 2) CHECK (salary_min >= 0),
    salary_max NUMERIC(14, 2) CHECK (salary_max >= 0),
    published_at TIMESTAMPTZ,
    collected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_min <= salary_max)
);

CREATE TABLE IF NOT EXISTS skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name TEXT NOT NULL CHECK (length(btrim(canonical_name)) > 0),
    normalized_name TEXT NOT NULL UNIQUE CHECK (length(btrim(normalized_name)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS job_skills (
    job_id BIGINT NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skills(skill_id),
    requirement_level TEXT NOT NULL DEFAULT 'unknown'
        CHECK (requirement_level IN ('required', 'desirable', 'mentioned', 'unknown')),
    evidence_text TEXT,
    review_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (review_status IN ('pending', 'reviewed', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (job_id, skill_id)
);

CREATE TABLE IF NOT EXISTS job_postings (
    posting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
    source_id BIGINT NOT NULL REFERENCES sources(source_id),
    collected_run_id BIGINT REFERENCES pipeline_runs(pipeline_run_id) ON DELETE SET NULL,
    external_job_id TEXT,
    original_url TEXT NOT NULL CHECK (length(btrim(original_url)) > 0),
    source_title TEXT,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (last_seen_at >= first_seen_at)
);

-- Duplicatas dentro de uma fonte: o ID externo prevalece quando existente.
CREATE UNIQUE INDEX IF NOT EXISTS uq_job_postings_external
    ON job_postings(source_id, external_job_id)
    WHERE external_job_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_job_postings_source_url
    ON job_postings(source_id, original_url);

CREATE INDEX IF NOT EXISTS idx_jobs_company ON jobs(company_id);
CREATE INDEX IF NOT EXISTS idx_jobs_published_at ON jobs(published_at);
CREATE INDEX IF NOT EXISTS idx_postings_job ON job_postings(job_id);
CREATE INDEX IF NOT EXISTS idx_postings_source ON job_postings(source_id);
CREATE INDEX IF NOT EXISTS idx_job_skills_skill ON job_skills(skill_id);

COMMIT;
